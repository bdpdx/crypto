class task_queue : public observed {

public:

	task_queue();
	virtual ~task_queue();
			
	/*	add_task() adds a task to the task queue and returns an id which identifies the task.
		In the event that in_params.in_flags specifies k_add_piggyback but does not specify
		k_add_multiple_notifications, add_task will return 0. */
	task_id_t add_task( add_task_params &in_params );

	/*	remove_task() removes an unscheduled task (or tasks) from the task queue.
	
		in_task_id:						If 0, all ids will match, otherwise only a specific task
										is matched.
		in_task_type:					If 0, all types will match, otherwise only a specific type
										is matched.
		in_send_abort_notification:		If true, removed tasks will have their completion procs
										called with an error of err_task_aborted.
		
		Note that calling remove_task( 0, 0, X ) will result in all tasks being removed. */
	void remove_task( task_id_t in_task_id, task_type_t in_task_type = 0, bool in_send_abort_notification = true );

	/*	reorder_task() allows you to move a queued task to another position in the task queue,
		either immediately after the task with id matching in_order_after_task_id, or to the
		head of the list if in_order_after_task_id is zero or not found on the pending task queue.
	*/
	void reorder_task( task_id_t in_task_id, task_id_t in_order_after_task_id = 0 );

	/*	run() reenables a task queue that has been shut down.  A newly created task queue is
		enabled by default so this call is only necessary if you have called shutdown() and
		wish to restart the queue. */
	void run();

	/*	shutdown() causes the immediate removal of all tasks in the task queue, shuts down any
		threads blocked in remove() and waits for the exit of all other handler threads (any thread
		handler checking handler_should_abort() will receive true at this point and should abort).
		Any add_task() calls made after shutdown() will raise an err_task_queue_shutdown exception.
		The queue may be restarted by a call to run().
		
		By default, the completion routines for queued tasks will be called with an error of
		err_task_aborted.  Setting in_send_abort_notifications to false will suppress this
		behavior. */
	void shutdown( bool in_send_abort_notifications = true );

	/*	Locking suspends any operations to the task queue.  Tasks that are currently being handled
		will complete, but pending tasks, additions, and removals will block until unlock() is
		called. */
//	void lock() { m_task_queue.lock(); }
//	void unlock() { m_task_queue.unlock(); }

	/*	become_active_handler_thread() converts the calling thread to a task handler.  This call
		will succeed even if the number of handler threads is already equal to
		m_max_handler_threads.
		
		The in_dont_join_this_thread_on_shutdown flag determines whether or not shutdown()
		will wait (via pthread_join()) for the thread calling become_active_handler_thread()
		to exit before exiting.  If the task_queue is going to be destroyed from a thread
		other than the one calling become_active_handler_thread(), set the
		in_dont_join_this_thread_on_shutdown flag to false. */
	void become_active_handler_thread( bool in_dont_join_this_thread_on_shutdown = true );
	
// methods that return information about the queue:

	/*	Returns the current number of task handler threads (some or all may be blocked). */
	__u32 current_task_handler_threads();

	/*	Returns true if the queue is shutdown. */
	bool is_shutdown();

	/*	Returns the number of task handler threads that the queue is permitted to create. */
	__s32 max_concurrent_task_handler_threads();
	
	/*	Returns the number of seconds an idle handler thread will block waiting for a task before
		exiting. */
	__u32 seconds_before_idle_task_handler_exits();

// methods that change queue behavior:

	/*	set_max_concurrent_task_handler_threads() sets the maximum number of task handler threads
		that can exist simultaneously.  When a task is added via add_task(), one of following
		things will happen:

		1.	If there is at least one handler thread blocked waiting for an insertion, then the
			task will be queued and a handler thread will be unblocked to service it immediately.
			
		2.	If there are no handler threads blocked waiting for insertion, then the handling of the
			task is as follows:
			
			a)	If the maximum concurrent thread limit has not been reached, then a new thread will
				be created and the task will be queued for immediate execution.
				
			b)	If the maximum concurrent thread limit has been reached, then the task will be
				queued and it will be picked up by the next available handler thread.
				
		The default behavior is to not bound the number of handler threads that can be created,
		and can be specified by passing -1 (k_unlimited) to indicate no upper bound on the number
		of handler threads.
		
		Caveats:
		
		It is assumed that calling add_task() means the caller *wants* the task executed.  For this
		reason, explicitly setting the maximum concurrent thread limit to zero indicates that
		add_task() should immediately execute the task and return upon completion. */
	void set_max_concurrent_task_handler_threads( __s32 in_max_handlers );

	/*	set_seconds_before_idle_task_handler_exits() sets the number of seconds an idle task
		handler thread will block waiting for a task to be inserted before exiting.  The default
		is ten minutes. */
	void set_seconds_before_idle_task_handler_exits( __u32 in_seconds );

protected:

	struct task_completion_notifier {
		bool										aborted;
		task_completion_proc						completion;
		void									   *context;
		task_id_t									task_id;
	};

	struct notify_task : public task {
		priority_queue<task_completion_notifier>	notify_list;			// a list of notifications to be made when the task completes
	};
	
	atomic_queue<void>								m_active_handler_no_join_threads;
	atomic_queue<void>								m_active_handler_threads;
	__u32											m_idle_task_handler_timeout;
	__s32											m_max_handler_threads;
	mutex											m_mutex_create_task;
	mutex											m_mutex_shutdown;
	mutex											m_mutex_shutting_down;
	task_id_t										m_next_task_id;
	priority_queue<notify_task>						m_scheduled_tasks;		// operations need to be done under m_task_queue mutex lock
	atomic_priority_cond_wait_queue<notify_task>	m_task_queue;

	__u32											m_shutdown			:	1;

	void thread_loop();
	void handle_task( notify_task *in_task );

	virtual void *copy_data( __u32 in_event, const void *in_data, __u32 in_data_size );

	static void create_task_thread( task_queue *in_queue );
	static void *task_thread_entry( task_queue *in_queue );
	static bool should_abort_callback( task_handler_params *in_params );
	static void progress_callback( task_handler_params *in_params, double in_percent_done, const char *in_description );
};


